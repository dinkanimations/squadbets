#!/usr/bin/env node
/**
 * Concatenates supabase/migrations/*.sql into one file for the SQL Editor fallback.
 * Usage: node scripts/bundle-migrations.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const migrationsDir = resolve(process.cwd(), "supabase/migrations");
const outPath = resolve(process.cwd(), "supabase/migrations-bundle.sql");

const files = readdirSync(migrationsDir)
  .filter((name) => name.endsWith(".sql"))
  .sort();

const parts = files.map((name) => {
  const content = readFileSync(resolve(migrationsDir, name), "utf8").trim();
  return `-- =============================================================================\n-- ${name}\n-- =============================================================================\n\n${content}`;
});

writeFileSync(
  outPath,
  `-- Generated by scripts/bundle-migrations.mjs — run in Supabase SQL Editor (in order)\n-- ${files.length} migration files\n\n${parts.join("\n\n")}\n`,
  "utf8",
);

console.log(`Wrote ${outPath} (${files.length} migrations)`);

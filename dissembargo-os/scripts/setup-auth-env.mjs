#!/usr/bin/env node
/**
 * Writes .env.local from environment variables (no manual file editing needed).
 *
 * Usage:
 *   NEXT_PUBLIC_SUPABASE_URL=https://xxx.supabase.co \
 *   NEXT_PUBLIC_SUPABASE_ANON_KEY=eyJ... \
 *   SUPABASE_SERVICE_ROLE_KEY=eyJ... \
 *   TEST_AUTH_EMAIL=you@example.com \
 *   TEST_AUTH_PASSWORD=your-password \
 *   node scripts/setup-auth-env.mjs
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { spawnSync } from "node:child_process";

const required = [
  "NEXT_PUBLIC_SUPABASE_URL",
  "NEXT_PUBLIC_SUPABASE_ANON_KEY",
  "SUPABASE_SERVICE_ROLE_KEY",
];

const missing = required.filter((key) => !process.env[key]?.trim());

if (missing.length > 0) {
  console.error("\nMissing required environment variables:\n");
  for (const key of missing) {
    console.error(`  - ${key}`);
  }
  console.error(`
Provide them inline when running this script:

  NEXT_PUBLIC_SUPABASE_URL=https://YOUR_REF.supabase.co \\
  NEXT_PUBLIC_SUPABASE_ANON_KEY=eyJ... \\
  SUPABASE_SERVICE_ROLE_KEY=eyJ... \\
  node scripts/setup-auth-env.mjs

Find values in Supabase Dashboard:
  Project Settings → API → Project URL
  Project Settings → API → anon public
  Project Settings → API → service_role (click Reveal)
`);
  process.exit(1);
}

const lines = [
  "# Generated by scripts/setup-auth-env.mjs",
  `NEXT_PUBLIC_SUPABASE_URL=${process.env.NEXT_PUBLIC_SUPABASE_URL.trim()}`,
  `NEXT_PUBLIC_SUPABASE_ANON_KEY=${process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY.trim()}`,
  `SUPABASE_SERVICE_ROLE_KEY=${process.env.SUPABASE_SERVICE_ROLE_KEY.trim()}`,
  "",
  `NEXT_PUBLIC_SITE_URL=${process.env.NEXT_PUBLIC_SITE_URL?.trim() || "http://localhost:3000"}`,
  "",
  "DISABLE_AUTH=false",
  "NEXT_PUBLIC_DISABLE_AUTH=false",
  "",
];

if (process.env.TEST_AUTH_EMAIL?.trim()) {
  lines.push(`TEST_AUTH_EMAIL=${process.env.TEST_AUTH_EMAIL.trim()}`);
}
if (process.env.TEST_AUTH_PASSWORD?.trim()) {
  lines.push(`TEST_AUTH_PASSWORD=${process.env.TEST_AUTH_PASSWORD.trim()}`);
}

const envPath = resolve(process.cwd(), ".env.local");
writeFileSync(envPath, `${lines.join("\n")}\n`, "utf8");
console.log(`\nWrote ${envPath}\n`);

const verify = spawnSync("node", ["scripts/verify-auth.mjs"], {
  stdio: "inherit",
  cwd: process.cwd(),
  env: process.env,
});

process.exit(verify.status ?? 1);
